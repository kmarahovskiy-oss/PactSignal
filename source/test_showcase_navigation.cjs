// DOM contract tests, not a browser or independent human usability test.
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const page=fs.readFileSync(process.argv[2],'utf8');
const script=page.match(/<script>([\s\S]*?)<\/script>/)[1];
let scrolls=0;
const make=()=>({listeners:{},attrs:{},active:false,addEventListener(k,v){this.listeners[k]=v},setAttribute(k,v){this.attrs[k]=v},scrollIntoView(){scrolls++},classList:{toggle(){}}});
const cards=['payment','closed','reply'].map((group,i)=>({...make(),id:'case-'+(i+1),dataset:{group,actionable:String(i!==1),risk:String(i===0),search:['lena','maya','theo'][i]},querySelector(){return {focus(){},addEventListener(){}}}}));
const buttons=['actionable','all','risk','closed'].map(filter=>({...make(),dataset:{filter},textContent:filter,classList:{contains(){return false},toggle(k,v){this.active=v}}}));
const search={...make(),value:''},count=make(),tour=make(),container={...make(),style:{},getBoundingClientRect:()=>({top:180})};
const toolbar={...make(),style:{}},back={...make(),hidden:true};let restoredY=null;
const link={...make(),getAttribute(){return '#case-2'}};
const document={querySelectorAll:s=>s==='.thread'?cards:s==='[data-filter]'?buttons:[link],querySelector:s=>({'#search':search,'#resultcount':count,'#tour':tour,'#cases':container,'.toolbar':toolbar,'#back-view':back,'#results-start':{getBoundingClientRect:()=>({top:-250})}}[s]),getElementById:id=>cards.find(c=>c.id===id)};
vm.runInNewContext(script,{document,window:{innerHeight:900,scrollY:425,scrollTo({top}){restoredY=top},matchMedia:()=>({matches:true})}});
assert.equal(scrolls,0,'initial load must preserve hero');
assert.equal(cards[1].hidden,true);
buttons[2].listeners.click();
assert.equal(scrolls,0,'sticky toolbar must not be used as scroll target');assert.equal(restoredY,75,'scroll uses normal-flow marker even when it is above viewport');
assert.equal(container.style.minHeight,'900px','short result lists retain viewport space');
buttons[3].listeners.click();
assert.equal(restoredY,75,'Closed returns to the same result-list origin');
assert.equal(cards[1].hidden,false);
assert.deepEqual(buttons.map(b=>b.attrs['aria-pressed']),['false','false','false','true']);
buttons[2].listeners.click();
assert.equal(cards.filter(c=>!c.hidden).length,1);
assert.deepEqual(buttons.map(b=>b.attrs['aria-pressed']),['false','false','true','false']);
search.value='absent';search.listeners.input();assert.match(count.textContent,/No cases match/);
search.value='maya';search.listeners.input();
const priorQuery=search.value;
const before=scrolls;search.listeners.input();assert.equal(scrolls,before,'typing must not move viewport');
let prevented=false;link.listeners.click({preventDefault(){prevented=true}});
assert.equal(prevented,true);assert.equal(cards[1].open,true);assert.equal(cards[1].hidden,false);assert.equal(search.value,'');
back.listeners.click();assert.equal(search.value,priorQuery,'back restores search');assert.equal(restoredY,425,'back restores prior scroll');assert.equal(cards[1].open,false,'back closes newly opened case');
search.value='absent';tour.listeners.click();assert.equal(search.value,'');assert.equal(cards[0].open,true);assert.equal(cards.filter(c=>!c.hidden).length,1);
assert.equal(count.attrs['aria-live'],'polite');
console.log('PASS: filter visibility and previous-view restoration assertions (DOM contract, not browser E2E)');
